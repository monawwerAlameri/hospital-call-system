function t(key) {
    return (TRANSLATIONS[LANG] && TRANSLATIONS[LANG][key]) || (TRANSLATIONS['en'][key]) || key;
}

function setLang(lang) {
    LANG = lang;
    localStorage.setItem('hcs_lang', lang);
    const html = document.documentElement;
    html.lang = lang;
    html.dir = lang === 'ar' ? 'rtl' : 'ltr';

    // Font switch
    if (lang === 'ar') {
        document.body.style.fontFamily = "'Cairo', 'Inter', sans-serif";
        html.classList.add('lang-ar');
        html.classList.remove('lang-en');
    } else {
        document.body.style.fontFamily = "'Inter', -apple-system, sans-serif";
        html.classList.add('lang-en');
        html.classList.remove('lang-ar');
    }

    applyTranslations();
    updateLangToggle();
    saveLangToBackend(lang);
    // Re-render dynamic content that contains translated strings
    if (typeof renderCodeGrids === 'function') renderCodeGrids();
    if (typeof renderCodeRefTable === 'function') renderCodeRefTable();
    if (typeof updateRecentCalls === 'function') updateRecentCalls();
    if (typeof updateCallFeed === 'function') updateCallFeed();
    if (typeof updateAllLogs === 'function') updateAllLogs();
    if (typeof updateAnalytics === 'function') updateAnalytics();
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = t(key);
        if (val) {
            if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
                const ph = el.getAttribute('data-i18n-placeholder');
                if (ph) el.placeholder = t(ph);
                else el.textContent = val;
            } else {
                el.textContent = val;
            }
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.getAttribute('data-i18n-title'));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
}

function updateLangToggle() {
    const btn = document.getElementById('langToggleBtn');
    if (btn) {
        btn.innerHTML = LANG === 'ar'
            ? '<i class="fas fa-globe"></i><span id="langBtnText">English</span>'
            : '<i class="fas fa-globe"></i><span id="langBtnText">العربية</span>';
        btn.title = LANG === 'ar' ? 'Switch to English' : 'التبديل إلى العربية';
    }
}

async function saveLangToBackend(lang) {
    try {
        await fetch('api/settings.php', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ ui_language: lang })
        });
    } catch (e) {}
}

function toggleLang() {
    setLang(LANG === 'en' ? 'ar' : 'en');
}

// Init on load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('hcs_lang') || 'en';
    setLang(savedLang);
});
